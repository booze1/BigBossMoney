import { cp, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Copies dist/ to build/, which is committed.
 *
 * GitHub Pages for this repo is in "deploy from a branch" mode, so the public
 * site is the branch's file tree rather than the artifact deploy-pages.yml
 * uploads. That tree's index.html is Vite's dev entry and cannot run as a
 * static file, so it redirects into build/ — a complete, self-contained copy of
 * the real build. See README, "Why build/ is committed".
 *
 * Once Settings -> Pages -> Source is switched to "GitHub Actions", this whole
 * mechanism is dead weight and build/ can be deleted.
 */
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const from = resolve(root, 'dist');
const to = resolve(root, 'build');

await rm(to, { recursive: true, force: true });
await cp(from, to, { recursive: true });
await writeFile(
  resolve(to, 'README.md'),
  'Generated by `npm run build:branch` — do not edit. This is a copy of dist/,\n' +
    'committed so the Pages branch build has something it can actually serve.\n',
);

console.log('build/ staged from dist/');
